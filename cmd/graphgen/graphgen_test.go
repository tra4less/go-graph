const (
	depPkg  = "github.com/tra4less/go-graph/cmd/graphgen/testdata/dep"
	usePkg  = "github.com/tra4less/go-graph/cmd/graphgen/testdata/use"
	dep2Pkg = "github.com/tra4less/go-graph/cmd/graphgen/testdata/x/dep2" // package dep
)

// The fixtures in testdata import go-graph, which this module does not
// require (graphgen itself never imports it, and a replace directive would
// break `go install ...@version`). Run the tests from the go-graph
// workspace, whose go.work provides it.

// fixtureOut is where the generated file of the fixture package would go.
// Tests never write it: they hand graphgen its content instead.
var fixtureOut = filepath.Join("testdata", "use", "operators_gen.go")

// gen writes spec to a temp file and generates for the fixture package
// testdata/use, as if no generated file existed yet.
func gen(t *testing.T, spec string) ([]byte, error) {
	return genOver(t, spec, nil)
}

// genOver is gen with existing as the current generated file.
func genOver(t *testing.T, spec string, existing []byte) ([]byte, error) {
	t.Helper()
	in := filepath.Join(t.TempDir(), "operators.yaml")
	if err := os.WriteFile(in, []byte(spec), 0o644); err != nil {
		t.Fatal(err)
	}
	return generateWith(in, fixtureOut, existing)
}

func TestGenerate(t *testing.T) {
	src, err := gen(t, `
x-dep: &dep `+depPkg+`
operators:
  local:  { package: `+usePkg+`, func: (*Local).Op }
  search: { package: *dep, func: (*Client).Search }
  value:  { package: *dep, func: Client.Value }
  free:   { package: *dep, func: Free }
  other:  { package: `+dep2Pkg+`, func: Other }
middleware:
  mw: { package: *dep, func: Mw }
entries:
  - { package: *dep, var: Entry }
`)
	if err != nil {
		t.Fatal(err)
	}
	got := string(src)
	for _, want := range []string{
		"// Code generated by graphgen from operators.yaml. DO NOT EDIT.",
		"\t\"" + depPkg + "\"\n",
		// The standard library apart, other imports sorted by path.
		"import (\n\terrors2 \"errors\"\n\n\t\"" + depPkg + "\"\n",
		// One field per receiver type; value and pointer receivers differ.
		// Each field names the components bound to it.
		"type Receivers struct {\n\tLocal   *Local      // local\n\tClient  *dep.Client // search\n\tClient2 dep.Client  // value\n}",
		// Its package name is dep, taken by the first import: named, though
		// the alias is the last element of the path.
		"\tdep2 \"" + dep2Pkg + "\"\n",
		`graph2 "github.com/tra4less/go-graph/graph"`,
		// r, errors and graph are taken by top-level vars of package use.
		"func Options(r2 Receivers) ([]graph2.Option, error) {",
		// Every nil pointer receiver is reported, prefixed by the package;
		// value receivers cannot be nil.
		`errs = append(errs, errors2.New("use: Receivers.Local is nil (needed by local)"))`,
		`errs = append(errs, errors2.New("use: Receivers.Client is nil (needed by search)"))`,
		`return nil, errors2.Join(errs...)`,
		// Grouped by kind: entries, operators, middleware.
		"\t\t// Entries.\n\t\tdep.Entry,\n\n\t\t// Operators.\n",
		"\n\n\t\t// Middleware.\n",
		`graph2.Op("local", r2.Local.Op),`, // own package: full path in YAML, unqualified in Go
		`graph2.Op("search", r2.Client.Search),`,
		`graph2.Op("value", r2.Client2.Value),`,
		`graph2.Op("free", dep.Free),`,
		`graph2.Op("other", dep2.Other),`,
		`graph2.Middleware("mw", dep.Mw),`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in:\n%s", want, got)
		}
	}

	// The generated file must compile in its package (given as an overlay,
	// so the source tree is never written).
	abs, err := filepath.Abs(fixtureOut)
	if err != nil {
		t.Fatal(err)
	}
	pkgs, err := packages.Load(&packages.Config{
		Mode:    packages.NeedTypes,
		Dir:     filepath.Dir(fixtureOut),
		Overlay: map[string][]byte{abs: src},
	}, ".")
	if err != nil || len(pkgs) != 1 || len(pkgs[0].Errors) > 0 {
		t.Fatalf("generated file does not compile: %v %v", err, pkgs[0].Errors)
	}

	if strings.Contains(got, "Client2 == nil") {
		t.Error("value receiver checked for nil")
	}

	// A stale generated file never blocks regeneration.
	stale := []byte("package use\n\nvar _ = removedFunc()\n")
	if _, err := genOver(t, "operators:\n  local: { package: "+usePkg+", func: (*Local).Op }\n", stale); err != nil {
		t.Errorf("stale file blocked generation: %v", err)
	}
}

func TestErrors(t *testing.T) {
	dep := "package: " + depPkg + ", "
	cases := []struct {
		name, spec, want string
	}{
		{"unknown top field", "operator: {}", `unknown field "operator"`},
		{"unknown decl field", "operators:\n  x: { " + dep + "fn: Free }", "field fn not found"},
		{"missing func", "operators:\n  x: { " + dep + "}", `missing "func"`},
		{"missing package", "operators:\n  x: { func: Free }", `missing "package"`},
		{"relative package", "operators:\n  x: { package: ./dep, func: Free }", "must be a full import path"},
		{"var in operators", "operators:\n  x: { " + dep + "var: Entry }", `use "func" here`},
		{"bad symbol", "operators:\n  x: { " + dep + "func: \"(*Client.Search\" }", "bad symbol"},
		{"duplicate", "operators:\n  x: { " + dep + "func: Free }\n  x: { " + dep + "func: Free }", `"x" declared twice`},
		{"nothing", "x-a: 1", "nothing declared"},
		{"old top-level func", "func: F\noperators: {}", `unknown field "func"`},
		{"no function", "operators:\n  x: { " + dep + "func: Nope }", "no function Nope"},
		{"no type", "operators:\n  x: { " + dep + "func: (*Nope).M }", "no type Nope"},
		{"no method", "operators:\n  x: { " + dep + "func: (*Client).Nope }", "has no method Nope"},
		{"pointer receiver", "operators:\n  x: { " + dep + "func: Client.Search }", "write (*Client).Search"},
		{"unexported", "operators:\n  x: { " + dep + "func: hidden }", "must be exported"},
		{"no ctx", "operators:\n  x: { " + dep + "func: NoCtx }", "want func(context.Context, In) (Out, error)"},
		{"cfg as a parameter", "operators:\n  x: { " + dep + "func: OldWith }", "want func(context.Context, In) (Out, error)"},
		{"not struct", "operators:\n  x: { " + dep + "func: NotStruct }", "input string is not a struct"},
		{"generic", "operators:\n  x: { " + dep + "func: Generic }", "generic functions"},
		{"bad middleware view", "middleware:\n  x: { " + dep + "func: BadMw }", "middleware input string is not a struct"},
		{"op as middleware", "middleware:\n  x: { " + dep + "func: Free }", "want func(context.Context, graph.Wrap[In]) error"},
		{"not an entry", "entries:\n  - { " + dep + "var: NotEntry }", "want *graph.Entry[In, Out]"},
		{"funcName removed", "funcName: F\noperators: {}", `unknown field "funcName"`},
		{"bad package", "operators:\n  x: { package: example.com/nope, func: F }", `package "example.com/nope" has errors`},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			t.Parallel() // each case loads packages, which is slow; none writes to testdata
			_, err := gen(t, c.spec)
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Fatalf("want %q, got %v", c.want, err)
			}
		})
	}
}

func TestErrorsReportedTogetherWithPositions(t *testing.T) {
	_, err := gen(t, "operators:\n  a: { package: "+depPkg+", func: Nope1 }\n  b: { package: "+depPkg+", func: Nope2 }\n")
	if err == nil {
		t.Fatal("want errors")
	}
	msg := err.Error()
	for _, want := range []string{"operators.yaml:2:3: " + depPkg + ".Nope1: no function", "operators.yaml:3:3: " + depPkg + ".Nope2: no function"} {
		if !strings.Contains(msg, want) {
			t.Errorf("missing %q in:\n%s", want, msg)
		}
	}
}

// The example's committed file must match what graphgen generates.
func TestExampleUpToDate(t *testing.T) {
	dir := filepath.Join("..", "..", "examples", "searchgen")
	err := run(filepath.Join(dir, "operators.yaml"), filepath.Join(dir, "operators_gen.go"), true)
	if errors.Is(err, errStale) {
		t.Fatal("examples/searchgen/operators_gen.go is stale: run go generate ./examples/searchgen")
	}
	if err != nil {
		t.Fatal(err)
	}
}

// Without pointer receivers nothing can be nil: no checks and no errors
// import.
func TestGenerateWithoutPointerReceivers(t *testing.T) {
	src, err := gen(t, "operators:\n  value: { package: "+depPkg+", func: Client.Value }\n  free: { package: "+depPkg+", func: Free }\n")
	if err != nil {
		t.Fatal(err)
	}
	got := string(src)
	for _, unwanted := range []string{`"errors"`, "errs", "It fails if"} {
		if strings.Contains(got, unwanted) {
			t.Errorf("unexpected %q in:\n%s", unwanted, got)
		}
	}
	if !strings.Contains(got, "import (\n\t\""+depPkg+"\"\n") {
		t.Errorf("imports:\n%s", got)
	}
}

// The generated names are fixed; a package that already declares one gets a
// clear error instead of a file that does not compile.
func TestGeneratedNameTaken(t *testing.T) {
	in := filepath.Join(t.TempDir(), "operators.yaml")
	if err := os.WriteFile(in, []byte("operators:\n  free: { package: "+depPkg+", func: Free }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	_, err := generateWith(in, filepath.Join("testdata", "taken", "operators_gen.go"), nil)
	if err == nil || !strings.Contains(err.Error(), "package taken already declares Options; generate into a separate package") {
		t.Fatalf("err %v", err)
	}
}
